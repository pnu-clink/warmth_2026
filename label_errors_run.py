import pandas as pd
import json
import os
import argparse
from openai import OpenAI
from tqdm import tqdm
from api_credentials import load_openai_key

client = None

# 기존 오류 분류 기준 유지
SYSTEM_PROMPT = """
You are an expert AI researcher building an automated error analysis framework to evaluate Large Language Models (LLMs).
You will be provided with a multiple-choice question from the MMLU-Pro dataset, its answer options, the true correct answer, and the incorrect reasoning text generated by an LLM.

Your task is to carefully analyze the model's incorrect reasoning text and classify the root cause of its failure into exactly ONE of the following 6 categories:

[Strict Error Categories]
1. Knowledge & Formula Misapplication: The model clearly lacks the core domain knowledge. It states incorrect facts, relies on false definitions, or uses the wrong formula from the very beginning.
2. Logical Derailment (Hallucination in CoT): The model possesses the correct initial facts or formulas, but the step-by-step logic breaks down. It contradicts itself, hallucinates fake intermediate steps, or makes an illogical leap to a wrong conclusion.
3. Token Limit Exceeded (Verbosity): The model generates overly verbose text and gets cut off before it can output the final answer.
4. Calculation / Arithmetic Error: The logic, formulas, and facts are perfectly correct, but the model makes a simple arithmetic computation mistake.
5. Generation Degeneration & Format Failure: The model's reasoning points clearly to the correct answer, but it completely fails to extract the correct letter at the end, or it falls into an infinite text repetition loop.
6. Others: Exceptional errors that strictly do not fit into any of the 5 categories above.

[Output Format]
You MUST respond strictly in the following JSON format. You must write the 'step_by_step_analysis' FIRST before assigning the 'error_category'.
{
    "step_by_step_analysis": "<Analyze whether the initial knowledge was correct, and exactly where the reasoning broke down>",
    "error_category": <integer between 1 and 6>,
    "reason": "<A concise 1-2 sentence final justification>"
}
"""

ERROR_NAMES = {
    1: "Knowledge & Formula Misapplication",
    2: "Logical Derailment (CoT Hallucination)",
    3: "Token Limit Exceeded (Verbosity)",
    4: "Calculation / Arithmetic Error",
    5: "Generation Degeneration & Format Failure",
    6: "Others",
}

# 출력 컬럼은 기존 구성 유지
KEEP_COLS = [
    "question_id",
    "category",
    "model_type",
    "correct_answer",
    "extracted_choice",
    "error_category",
    "reason",
]


def classify(question, options_json, correct_answer, model_text, judge_model):
    user_prompt = (
        f"[Question]\n{question}\n\n"
        f"[Options (JSON)]\n{options_json}\n\n"
        f"[Correct Answer]\n{correct_answer}\n\n"
        f"[Model's Incorrect Reasoning]\n{model_text}"
    )

    try:
        r = client.chat.completions.create(
            model=judge_model,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            response_format={"type": "json_object"},
            temperature=0.1,
        )
        return json.loads(r.choices[0].message.content), False

    except Exception as e:
        return {
            "error_category": 6,
            "reason": f"API_ERROR: {e}",
        }, True


def main():
    global client

    ap = argparse.ArgumentParser(
        description="질문·선택지·정답·모델 답변을 이용한 오답 오류유형 라벨링"
    )
    ap.add_argument("filename", help="평가 결과 CSV")
    ap.add_argument(
        "--env-file",
        default=None,
        help="Private .env file; defaults to the project-root .env. Do not pass a key on the command line.",
    )
    ap.add_argument("--judge_model", default="gpt-4o")
    ap.add_argument("--out", default=None)
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--resume", action="store_true")
    ap.add_argument("--save_every", type=int, default=25)
    args = ap.parse_args()

    client = OpenAI(api_key=load_openai_key(args.env_file))
    out_path = args.out or args.filename.replace(".csv", "_LABELED.csv")

    df = pd.read_csv(args.filename)

    # 질문이나 선택지가 누락된 상태로 라벨링하지 않도록 확인
    required_cols = [
        "is_correct",
        "question",
        "options_json",
        "correct_answer",
        "answer_text",
    ]
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"입력 CSV에 필요한 컬럼이 없습니다: {missing_cols}")

    errs = df[df["is_correct"].isin([0, False, "0", "False"])].copy()
    errs = errs.reset_index(drop=True)

    if args.limit:
        errs = errs.head(args.limit)

    # 실제 대상 오답의 입력 문맥이 비어 있으면 실행 중단
    for col in ["question", "options_json", "correct_answer", "answer_text"]:
        invalid = (
            errs[col].isna()
            | errs[col].astype(str).str.strip().eq("")
        )
        if invalid.any():
            raise ValueError(
                f"대상 오답 중 '{col}'이 비어 있는 행이 "
                f"{int(invalid.sum())}개 있습니다."
            )

    print(f"{'=' * 62}")
    print(f"🏷️  오류유형 라벨링 | judge={args.judge_model}")
    print(f"   입력: {args.filename}")
    print(
        f"   대상 오답: {len(errs)}건 "
        f"| 조건: "
        f"{list(errs['model_type'].unique()) if 'model_type' in errs else ['?']}"
    )
    print("   Judge 입력: 질문 + 선택지 + 정답 + 모델 답변")
    print(f"{'=' * 62}")

    # 이어하기
    done = {}

    if args.resume and os.path.exists(out_path):
        prev = pd.read_csv(out_path)
        keys = [
            c for c in ["question_id", "model_type"]
            if c in prev.columns
        ]

        for _, row in prev.iterrows():
            if pd.notna(row.get("error_category")):
                done[tuple(row[c] for c in keys)] = (
                    row["error_category"],
                    row.get("reason", ""),
                )

        print(f"♻️  이어하기: {len(done)}건 완료됨\n")

    keys = [
        c for c in ["question_id", "model_type"]
        if c in errs.columns
    ]

    cats, reasons, n_fail = [], [], 0

    for _, row in tqdm(
        errs.iterrows(),
        total=len(errs),
        desc="라벨링",
    ):
        k = tuple(row[c] for c in keys)

        if k in done:
            cats.append(done[k][0])
            reasons.append(done[k][1])
            continue

        res, failed = classify(
            question=row["question"],
            options_json=row["options_json"],
            correct_answer=row["correct_answer"],
            model_text=row["answer_text"],
            judge_model=args.judge_model,
        )

        n_fail += failed
        cats.append(res.get("error_category", 6))
        reasons.append(res.get("reason", ""))

        if len(cats) % args.save_every == 0:
            tmp = errs.iloc[:len(cats)].copy()
            tmp["error_category"] = cats
            tmp["reason"] = reasons

            tmp[
                [c for c in KEEP_COLS if c in tmp.columns]
            ].to_csv(
                out_path,
                index=False,
                encoding="utf-8-sig",
            )

    errs["error_category"] = cats
    errs["reason"] = reasons

    errs[
        [c for c in KEEP_COLS if c in errs.columns]
    ].to_csv(
        out_path,
        index=False,
        encoding="utf-8-sig",
    )

    print(f"\n{'=' * 62}")
    print(f"✅ 완료 → {out_path}")

    if n_fail:
        print(
            f"⚠️  API 실패 {n_fail}건이 범주 6으로 저장되었습니다. "
            "해당 행은 별도로 확인해야 합니다."
        )

    vc = errs["error_category"].value_counts().sort_index()
    print("\n[오류유형 분포]")

    for c, n in vc.items():
        print(
            f"   {int(c)}. {ERROR_NAMES.get(int(c), '?'):<42} "
            f"{n:>5} ({n / len(errs) * 100:5.1f}%)"
        )

    print("=" * 62)


if __name__ == "__main__":
    main()
